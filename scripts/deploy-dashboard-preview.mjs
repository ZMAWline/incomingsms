#!/usr/bin/env node
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const args = parseArgs(process.argv.slice(2));
const repoRoot = path.resolve(new URL('..', import.meta.url).pathname);
const dashboardDir = path.join(repoRoot, 'src', 'dashboard');
const sourceConfig = path.join(dashboardDir, 'wrangler.toml');
const prNumber = normalizePrNumber(args.pr || process.env.PR_NUMBER || process.env.GITHUB_EVENT_PULL_REQUEST_NUMBER);
const workerName = args.name || (prNumber ? `dashboard-pr-${prNumber}` : null);
const commitSha = args.sha || process.env.GITHUB_SHA || 'local';
const workersDevSubdomain = args.workersDevSubdomain || process.env.WORKERS_DEV_SUBDOMAIN || 'zalmen-531';
const command = args._[0] || 'generate';

if (!workerName) {
  fail('Missing PR number/name. Pass --pr <number> or --name dashboard-pr-<number>.');
}

const generatedDir = dashboardDir;
const generatedConfig = path.join(generatedDir, `${workerName}.wrangler.toml`);
const previewUrl = `https://${workerName}.${workersDevSubdomain}.workers.dev`;

if (command === 'generate') {
  fs.mkdirSync(generatedDir, { recursive: true });
  fs.writeFileSync(generatedConfig, buildPreviewConfig({ workerName, commitSha, previewUrl }));
  writeOutput('config_path', generatedConfig);
  writeOutput('worker_name', workerName);
  writeOutput('preview_url', previewUrl);
  console.log(`Generated ${path.relative(repoRoot, generatedConfig)}`);
  console.log(`Worker: ${workerName}`);
  console.log(`Preview URL: ${previewUrl}`);
  process.exit(0);
}

if (command === 'deploy') {
  ensureConfig();
  const deployArgs = ['wrangler', 'deploy', '--config', generatedConfig];
  if (args.dryRun) deployArgs.push('--dry-run');
  run('npx', deployArgs, { cwd: dashboardDir });
  writeOutput('config_path', generatedConfig);
  writeOutput('worker_name', workerName);
  writeOutput('preview_url', previewUrl);
  process.exit(0);
}

if (command === 'delete') {
  const deleteArgs = ['wrangler', 'delete', workerName, '--force'];
  if (args.dryRun) deleteArgs.push('--dry-run');
  run('npx', deleteArgs, { cwd: dashboardDir });
  writeOutput('worker_name', workerName);
  process.exit(0);
}

fail(`Unknown command: ${command}. Use generate, deploy, or delete.`);

function ensureConfig() {
  if (!fs.existsSync(generatedConfig)) {
    fs.mkdirSync(generatedDir, { recursive: true });
    fs.writeFileSync(generatedConfig, buildPreviewConfig({ workerName, commitSha, previewUrl }));
  }
}

function buildPreviewConfig({ workerName, commitSha, previewUrl }) {
  const raw = fs.readFileSync(sourceConfig, 'utf8');
  const lines = raw.split(/\r?\n/);
  const testStart = lines.findIndex((line) => /^\[env\.test\]$/.test(line.trim()));
  if (testStart < 0) fail(`${sourceConfig} does not contain [env.test].`);

  const top = lines.slice(0, testStart).filter((line) => {
    const t = line.trim();
    if (t === '') return true;
    if (t.startsWith('#')) return true;
    return /^(main|compatibility_date|account_id|workers_dev)\s*=/.test(t);
  });

  const transformed = lines.slice(testStart).map((line) => {
    const trimmed = line.trim();
    if (trimmed === '[env.test]') return '';
    if (trimmed.startsWith('[env.test.')) return line.replace('[env.test.', '[');
    if (trimmed.startsWith('[[env.test.')) return line.replace('[[env.test.', '[[');
    if (/^name\s*=/.test(trimmed)) return `name = "${workerName}"`;
    return line;
  });

  const previewVars = [
    'DASHBOARD_PREVIEW_MODE = "true"',
    `DASHBOARD_PREVIEW_WORKER = "${workerName}"`,
    `DASHBOARD_PREVIEW_COMMIT_SHA = "${commitSha}"`,
    `DASHBOARD_PREVIEW_URL = "${previewUrl}"`,
  ];
  const varsIndex = transformed.findIndex((line) => line.trim() === '[vars]');
  if (varsIndex >= 0) {
    transformed.splice(varsIndex + 1, 0, ...previewVars);
  } else {
    transformed.unshift('[vars]', 'WING_EXPECTED_RATE = "5.00"', ...previewVars, '');
  }

  const output = [
    '# Generated by scripts/deploy-dashboard-preview.mjs; do not edit by hand.',
    '# Uses the dashboard TEST environment bindings under a per-PR Worker name.',
    ...top,
    '',
    ...transformed,
    '',
  ].join('\n');

  // Collapse accidental duplicate empty lines around removed [env.test].
  return output.replace(/\n{3,}/g, '\n\n');
}

function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (!arg.startsWith('--')) {
      out._.push(arg);
      continue;
    }
    const [key, inlineValue] = arg.slice(2).split('=', 2);
    const camelKey = key.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
    if (inlineValue !== undefined) {
      out[camelKey] = inlineValue;
    } else if (i + 1 < argv.length && !argv[i + 1].startsWith('--')) {
      out[camelKey] = argv[++i];
    } else {
      out[camelKey] = true;
    }
  }
  return out;
}

function normalizePrNumber(value) {
  if (value === undefined || value === null || value === '') return null;
  const s = String(value).trim();
  if (!/^\d+$/.test(s)) fail(`Invalid PR number: ${s}`);
  return s;
}

function run(cmd, cmdArgs, options) {
  const res = spawnSync(cmd, cmdArgs, { ...options, stdio: 'inherit', env: process.env });
  if (res.status !== 0) process.exit(res.status ?? 1);
}

function writeOutput(name, value) {
  if (process.env.GITHUB_OUTPUT) {
    fs.appendFileSync(process.env.GITHUB_OUTPUT, `${name}=${value}${os.EOL}`);
  }
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
